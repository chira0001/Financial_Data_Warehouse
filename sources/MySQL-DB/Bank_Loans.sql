CREATE TABLE IF NOT EXISTS loans (
    loan_id INT PRIMARY KEY,
    customer_id INT NOT NULL,
    account_id INT,
    loan_type VARCHAR(50),
    loan_amount DECIMAL(15,2),
    interest_rate DECIMAL(5,2),
    loan_start_date DATE,
    loan_end_date DATE,
