    payment_id INT PRIMARY KEY,
    loan_id INT NOT NULL,
    payment_date DATE,
    payment_amount DECIMAL(15,2),
    payment_method VARCHAR(30),
    payment_status VARCHAR(30),
    FOREIGN KEY (loan_id) REFERENCES loans(loan_id)
);

